/**
 * Pure domain entities and types for the Engineering, Backlog & Sprints Module
 * (AI Coder and AI Product).
 *
 * Directly mirrors the production schema from Supabase:
 * `project_tasks`, `projects`, `employees`, and `audit_logs`.
 *
 * Hexagonal architecture: pure domain models, completely decoupled from
 * Supabase, Next.js, React, or third-party SDKs.
 */

export type TaskColumnStatus = 'To Do' | 'In Progress' | 'In Review' | 'Blocked' | 'Done';

export type TaskPriority = 'LOW' | 'MED' | 'HIGH' | 'URGENT';

export interface ProjectTask {
  id: string;
  code: string;
  title: string;
  columnStatus: TaskColumnStatus;
  priority: TaskPriority;
  projectId?: string;
  projectName?: string;
  projectCode?: string;
  assignedUserId?: string;
  updatedAt?: string;
}

export interface Project {
  id: string;
  code: string;
  name: string;
  status: string;
  customerId?: string;
  description?: string;
  startDate?: string;
  endDate?: string;
}

/**
 * Proposed task status transition generated by the AI Coder when reconciling
 * the backlog board with real forge activity (branches, commits, pull requests).
 *
 * In accordance with ADR-0028 (AI -> AI -> AI -> HUMAN), this status change is
 * held behind a Human Approval Gate (`scope_baseline`) before writing to the database.
 */
export interface TaskSyncProposal {
  taskId: string;
  code: string;
  title: string;
  currentStatus: TaskColumnStatus;
  proposedStatus: TaskColumnStatus;
  reason: string;
  linkedBranch?: string;
  linkedCommits: string[];
  linkedChangeRequests?: string[];
  blockedBy?: string;
}

export interface SprintSyncReport {
  tasksScannedCount: number;
  byStatus: Record<string, number>;
  proposals: TaskSyncProposal[];
  appliedCount: number;
  skippedCount: number;
  generatedAt: string;
}

export interface AcceptanceCriterion {
  id: string;
  given: string;
  when: string;
  then: string;
}

export type HexagonalLayer = 'domain' | 'application' | 'infrastructure';

export interface SpecSection {
  id: string;
  title: string;
  requirement: string;
  criteria: AcceptanceCriterion[];
  layers: HexagonalLayer[];
  risks: string[];
}

export interface MilestoneSpecReport {
  projectId: string;
  projectName: string;
  taskIds: string[];
  taskCodes: string[];
  scope: string;
  specSections: SpecSection[];
  outOfScope: string[];
  openQuestions: string[];
  /** Technical specification formatted as clean YAML ready for repository version control. */
  yaml: string;
  generatedAt: string;
}

export interface SprintSyncJobResult {
  jobId: string;
  stage: 'coder';
  requiresApproval: boolean;
  approvalGateId: string;
  report: SprintSyncReport;
  createdAt: string;
}

export interface MilestoneSpecJobResult {
  jobId: string;
  stage: 'product';
  requiresApproval: false;
  report: MilestoneSpecReport;
  createdAt: string;
}